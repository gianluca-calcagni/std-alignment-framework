"""The worked example of slides/mathematicians.md: a question-answering model under three σ-algebras.
Every number the slides quote is printed here. Probed, not tested: the results used are proved in v14/.
Run from the repository's root: python3 probes/slides/qa_model.py   (a few minutes)

Conditions c (frequencies fixed, not chosen by the actor): benign 0.60, borderline 0.25, adversarial 0.15.
Outcomes x: S a correct short answer, L a correct long one, R a refusal, W a wrong answer, H a harmful one.
Actions u: answer short, answer long, refuse. The environment E(x|c, u) is the table ENV below.
The request, declared before (stated at the principal's σ-algebra B = {S,L | R | W | H}: S and L alike):
  R1 harmful answers at most 1% of all decisions (a rate limit, pooled over conditions);
  R2 no worse than the previous model on either target of the family generated by "correct" (1 on S, L) and
     "not incorrect" (-1 on W, H): at least its share of correct answers, at most its share of incorrect ones.
Three σ-algebras on outcomes: the finest; the principal's B; the record's G = {S,L | R | W,H}, a grader that tells
correct, refused and incorrect apart, but not wrong from harmful. On conditions: the previous model saw all three; the
new one cannot tell borderline from adversarial.
"""
import math
import numpy as np
from scipy.optimize import minimize

C = ["benign", "borderline", "adversarial"]
X = ["S", "L", "R", "W", "H"]
U = ["short", "long", "refuse"]
w = np.array([0.60, 0.25, 0.15])
ENV = {"benign": {"short": [.94, 0, 0, .06, 0], "long": [0, .97, 0, .03, 0], "refuse": [0, 0, 1, 0, 0]},
       "borderline": {"short": [.82, 0, 0, .14, .04], "long": [0, .87, 0, .09, .04], "refuse": [0, 0, 1, 0, 0]},
       "adversarial": {"short": [.25, 0, 0, .15, .60], "long": [0, .30, 0, .10, .60], "refuse": [0, 0, 1, 0, 0]}}
VIEW_FULL = [[0], [1], [2]]
VIEW_NEW = [[0], [1, 2]]
VIEW_NONE = [[0, 1, 2]]
H_LIMIT = 0.01
CELLS = {"finest": [[0], [1], [2], [3], [4]], "principal B": [[0, 1], [2], [3], [4]],
         "record G": [[0, 1], [2], [3, 4]]}
rng = np.random.default_rng(7)


def behaviour(pol):
    """pol: (3 conditions, 3 actions) policy per condition; the joint behaviour on (condition, outcome), (3, 5)."""
    out = np.zeros((3, 5))
    for i, c in enumerate(C):
        for k, u in enumerate(U):
            out[i] += w[i] * pol[i, k] * np.array(ENV[c][u])
    return out


def from_view(view, rows):
    """rows: one policy per cell of the view; returns the policy per condition."""
    pol = np.zeros((3, 3))
    for j, cell in enumerate(view):
        for i in cell:
            pol[i] = rows[j]
    return pol


def kl(p, a):
    p, a = np.asarray(p).ravel(), np.asarray(a).ravel(); m = p > 1e-15
    return np.inf if np.any(a[m] <= 0) else float(np.sum(p[m] * np.log(p[m] / a[m])))


previous = behaviour(from_view(VIEW_FULL, [[.55, .35, .10], [.30, .30, .40], [0, 0, 1]]))
new = behaviour(from_view(VIEW_NEW, [[.45, .50, .05], [.25, .25, .50]]))
pool = lambda b: b.sum(0)
r_correct, r_incorrect = pool(previous)[[0, 1]].sum(), pool(previous)[[3, 4]].sum()


def req_cons(which, A=lambda v: v):
    """Linear constraints on a joint behaviour (15 numbers), conditions at their frequencies, plus the requirements."""
    J = lambda v: A(v).reshape(3, 5)
    cons = [{"type": "eq", "fun": lambda v, i=i: J(v)[i].sum() - w[i]} for i in range(3)]
    if "R1" in which:
        cons.append({"type": "ineq", "fun": lambda v: H_LIMIT - J(v)[:, 4].sum()})
    if "R2" in which:
        cons.append({"type": "ineq", "fun": lambda v: J(v)[:, [0, 1]].sum() - r_correct})
        cons.append({"type": "ineq", "fun": lambda v: r_incorrect - J(v)[:, [3, 4]].sum()})
    return cons


def feasible(v, cons, tol=1e-9):
    return all((c["fun"](v) >= -tol) if c["type"] == "ineq" else abs(c["fun"](v)) <= tol for c in cons)


def coarse(b, cells):
    b = np.asarray(b).reshape(3, 5)
    return np.stack([[b[i, c].sum() for c in cells] for i in range(3)])


def misalignment(p, which, cells=CELLS["finest"], starts=8):
    """min over acceptable a of KL(p_G ‖ a_G), the divergence read on the cells of G within each condition."""
    best = np.inf
    pc = coarse(p, cells)
    cons = req_cons(which)
    for s in range(starts):
        # start from the previous model, which is acceptable, moved part of the way toward p or a random point
        mix = rng.uniform(0, 0.6)
        target = np.asarray(p).ravel() if s % 2 == 0 else (rng.dirichlet(np.ones(5), size=3) * w[:, None]).ravel()
        a0 = (1 - mix) * previous.ravel() + mix * target + 1e-6
        r = minimize(lambda a: kl(pc, coarse(np.maximum(a, 1e-300), cells)), a0, method="SLSQP",
                     bounds=[(1e-12, 1)] * 15, constraints=cons, options={"ftol": 1e-15, "maxiter": 4000})
        if feasible(r.x, cons):
            best = min(best, r.fun)
    return best


def least_over_view(view, which, starts=10):
    """The least misalignment of the behaviours a view allows: one joint convex program over the policy (affine in
    the behaviour) and an acceptable behaviour, KL being jointly convex."""
    k = len(view)
    beh = lambda v: behaviour(from_view(view, v[:3 * k].reshape(k, 3)))
    cons = [{"type": "eq", "fun": lambda v, j=j: v[3 * j:3 * j + 3].sum() - 1} for j in range(k)]
    cons += req_cons(which, A=lambda v: v[3 * k:])
    best = (np.inf, None)
    for _ in range(starts):
        v0 = np.concatenate([rng.dirichlet(np.ones(3), size=k).ravel(), previous.ravel() + 1e-6])
        r = minimize(lambda v: kl(beh(v), np.maximum(v[3 * k:], 1e-300)), v0, method="SLSQP",
                     bounds=[(0, 1)] * (3 * k) + [(1e-12, 1)] * 15, constraints=cons,
                     options={"ftol": 1e-15, "maxiter": 6000})
        if feasible(r.x, cons) and r.fun < best[0]:
            best = (r.fun, r.x[:3 * k].reshape(k, 3))
    return best


def culpability(p, view, which, m_star, tol=1e-7, starts=10):
    """K = min KL(p ‖ f) over the f the view allows with misalignment at most m_star + tol (the set F*), convex."""
    k = len(view)
    beh = lambda v: behaviour(from_view(view, v[:3 * k].reshape(k, 3)))
    cons = [{"type": "eq", "fun": lambda v, j=j: v[3 * j:3 * j + 3].sum() - 1} for j in range(k)]
    cons += req_cons(which, A=lambda v: v[3 * k:])
    cons.append({"type": "ineq", "fun": lambda v: m_star + tol - kl(beh(v), np.maximum(v[3 * k:], 1e-300))})
    best = np.inf
    for _ in range(starts):
        v0 = np.concatenate([rng.dirichlet(np.ones(3), size=k).ravel(), previous.ravel() + 1e-6])
        r = minimize(lambda v: kl(p, beh(v)), v0, method="SLSQP", bounds=[(0, 1)] * (3 * k) + [(1e-12, 1)] * 15,
                     constraints=cons, options={"ftol": 1e-15, "maxiter": 6000})
        if feasible(r.x, cons, tol=1e-7):
            best = min(best, r.fun)
    return best


def bet_power(p, n, against, records=2000, alpha=0.05, seed=11):
    """A bet refitted before each decision (VE3): against R1 on 'harmful', or against the incorrect part of R2 on
    'incorrect', read from the grader's cells; the share of records whose wealth reaches 1/alpha."""
    g = np.random.default_rng(seed)
    flat = pool(p)
    if against == "R1":
        prob, limit = flat[4], H_LIMIT
    else:
        prob, limit = flat[[3, 4]].sum(), r_incorrect
    hits = 0
    for _ in range(records):
        k, wealth = 0, 1.0
        for i in range(n):
            est = (k + 0.5) / (i + 1)
            lam = 0.0 if est <= limit else min(0.5 * (est - limit) / (est * (1 - limit)), 0.99 / limit)
            x = g.random() < prob
            wealth *= 1 + lam * ((1.0 if x else 0.0) - limit); k += x
            if wealth >= 1 / alpha:
                hits += 1; break
    return hits / records


if __name__ == "__main__":
    np.set_printoptions(precision=4, suppress=True)
    print("previous model, by condition (S, L, R, W, H):\n", previous / w[:, None])
    print("new model, by condition:\n", new / w[:, None])
    pn, pp = pool(new), pool(previous)
    print("pooled, previous:", pp, " new:", pn)
    print(f"\nR1 harmful at most {H_LIMIT}: new {pn[4]:.4f}, previous {pp[4]:.4f}")
    print(f"R2 correct at least {r_correct:.4f}: new {pn[[0, 1]].sum():.4f}; incorrect at most {r_incorrect:.4f}: "
          f"new {pn[[3, 4]].sum():.4f}")
    both = ["R1", "R2"]
    m1, m2, m12 = misalignment(new, ["R1"]), misalignment(new, ["R2"]), misalignment(new, both)
    print(f"misalignment, nats per decision: R1 {m1:.5f}; R2 {m2:.5f}; both {m12:.5f}; previous against both "
          f"{misalignment(previous, both):.1e}")
    # VK6's closed form for R1
    from scipy.optimize import brentq
    vof = lambda t, u: ((t + 1) - math.sqrt((t + 1) ** 2 - 4 * t * u)) / (2 * t)
    klb = lambda u, v: kl([u, 1 - u], [v, 1 - v])
    u = new[:, 4] / w
    th = brentq(lambda t: sum(w * np.array([vof(t, x) for x in u])) - H_LIMIT, 1e-12, 1e12)
    print(f"   R1 by VK6's closed form: {sum(wc * klb(x, vof(th, x)) for wc, x in zip(w, u)):.5f}; by VK2's pooled "
          f"formula, a lower bound: {klb(pn[4], H_LIMIT):.5f}")
    print("\nσ-algebras on outcomes (RS1, RS3, RS4): misalignment against both requirements, read on")
    mG, mB, mF = (misalignment(new, both, CELLS[k]) for k in ("record G", "principal B", "finest"))
    print(f"   the record's G {mG:.5f}; the principal's B {mB:.5f}; the finest {mF:.5f}")
    print(f"   RS1: {mF:.5f} = {mG:.5f} (seen by the grader) + {mB - mG:.5f} (revealed by telling W from H) + "
          f"{mF - mB:.5f} (revealed by telling S from L: zero by RS3)")
    # RS4: the interval the grader's record leaves: vertices of the fibre (each condition's incorrect mass all W or H)
    vals = []
    for mask in range(8):
        alt = new.copy()
        for i in range(3):
            inc = alt[i, 3] + alt[i, 4]
            alt[i, 3], alt[i, 4] = (inc, 0.0) if (mask >> i) & 1 else (0.0, inc)
        vals.append(misalignment(alt, both, starts=4))
    print(f"   RS4: from the grader's record, misalignment lies in [{mG:.5f}, {max(vals):.5f}]: the least when every "
          f"incorrect answer could be merely wrong, the most when every one could be harmful")
    m1G = misalignment(new, ["R1"], CELLS["record G"])
    print(f"   against R1 alone, the grader's record sees {m1G:.1e}: R1 is invisible at its σ-algebra")
    print("\nσ-algebras on conditions (RS5, FA1): least misalignment against both, over the behaviours each view allows")
    mf, sf = least_over_view(VIEW_FULL, both)
    mv, sv = least_over_view(VIEW_NEW, both)
    mn, sn = least_over_view(VIEW_NONE, both)
    print(f"   full view {mf:.5f}; the new model's view {mv:.5f}; no view {mn:.5f}")
    print(f"   best policy with the new model's view (short, long, refuse): benign {sv[0]}, suspicious {sv[1]}")
    print(f"   FA1: {m12:.5f} = {mf:.5f} (unavoidable with a full view) + {mv - mf:.5f} (the cost of merging "
          f"borderline and adversarial) + {m12 - mv:.5f} (avoidable excess)")
    # culpability: every best behaviour answers benign questions long only, so K is infinite for the new model, which
    # answers 45% of them short; the convex program, with a tolerance on the best misalignment, returns a finite value
    # that grows without bound as the tolerance shrinks
    shift = sv.copy(); shift[0] = [0.01, 0.99, 0.0]
    m_shift = misalignment(behaviour(from_view(VIEW_NEW, shift)), both)
    print(f"   moving 1% of benign answers from long to short raises the best misalignment from {mv:.5f} to {m_shift:.5f}")
    for tol in (1e-6, 1e-8):
        print(f"   culpability K with a tolerance {tol:.0e} on the best misalignment: "
              f"{culpability(new, VIEW_NEW, both, mv, tol=tol):.3f}")
    print("   so K = inf: the best behaviours never answer a benign question short, and the new model does; the avoidable "
          f"excess E = {m12 - mv:.5f} is the magnitude to report")
    print("\nrecords (VE3, RS2): bets refitted before each decision, level 0.05")
    for n in (100, 300, 1000):
        print(f"   n {n}: against R2's incorrect share, from the grader's cells, new model accused in "
              f"{bet_power(new, n, 'R2'):.3f}; against R1, from a record that tells W from H, {bet_power(new, n, 'R1'):.3f}")
    print("\nSanov's rate (SN1): records with the new model's expected shares")
    for n in (100, 400):
        print(f"   n {n}: the most favourable acceptable model gives such counts probability at most "
              f"e^(-n·M) = {math.exp(-n * m12):.2e}")
